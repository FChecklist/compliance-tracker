#!/usr/bin/env node
// WO-DPDP-012 §5: generate the UNPUBLISHED drafts under dpdp-app/drafts/.
//
//   node scripts/generate-job-pages.mjs          write every draft
//   node scripts/generate-job-pages.mjs --check  exit 1 if any draft on disk
//                                                differs from what would be
//                                                generated (CI: the library
//                                                changed, regenerate)
//   node scripts/generate-job-pages.mjs --print-tables
//                                                dump the LAWS/PARTS/AREA_HELP
//                                                tables as JSON (drafts.test.ts
//                                                pins them to view-model.ts)
//
// Plain Node, zero dependencies, and NOT part of `bun run build`: drafts are
// not a Vite input, not under public/, not in any sitemap. Everything is
// derived from data/dpdp-library-<version>.json plus the content modules in
// scripts/draft-content/ -- nothing in a job page is retyped. Output is
// byte-stable across runs (the only dates are the library's exportedAt and
// the guides' fixed drafting date), which is what makes --check meaningful.
//
// What it writes:
//   drafts/jobs/<product>/<key>/index.html + index.md   one per library template
//   drafts/guides/<slug>/index.html + index.md           the seven WO §5 guides
//   drafts/hi/<dpdp-firm|dpdp-institution>/index.html + index.md
//   drafts/hi/guides/<slug>/index.html + index.md        five guides in Hindi
//   drafts/INDEX.md                                      a table of contents
// It never touches public/, src/, index.html or vite.config.ts.

import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve } from "node:path"
import { fileURLToPath } from "node:url"

import { AREA_HELP, LAWS, PARTS } from "./draft-content/law.mjs"
import { jobPage } from "./draft-content/jobs.mjs"
import { guidesEn } from "./draft-content/guides.en.mjs"
import { guidesHi, landingHi } from "./draft-content/hi.mjs"
import { renderHtml, renderMarkdown } from "./draft-content/render.mjs"

const APP_DIR = fileURLToPath(new URL("../", import.meta.url))
export const LIBRARY_FILE = "dpdp-library-0.2-wo010.json"
const DATA_FILE = join(APP_DIR, "data", LIBRARY_FILE)
const DRAFTS_DIR = join(APP_DIR, "drafts")

/** Build every draft in memory: Map<relative path (posix), content>. */
export function buildDrafts(libraryPath = DATA_FILE) {
  const lib = JSON.parse(readFileSync(libraryPath, "utf8"))
  if (!Array.isArray(lib.templates) || !lib.version || !lib.exportedAt) throw new Error(`${libraryPath}: not a library export`)
  const byKey = new Map(lib.templates.map((t) => [t.key, t]))
  const out = new Map()
  const toc = { jobs: [], guides: [], hi: [] }

  function put(dir, page) {
    const html = renderHtml(page)
    const md = renderMarkdown(page)
    for (const [name, body] of [["index.html", html], ["index.md", md]]) {
      const rel = `${dir}/${name}`
      if (out.has(rel)) throw new Error(`duplicate draft path ${rel}`)
      out.set(rel, body)
    }
    return `${dir}/index.html`
  }

  const templates = [...lib.templates].sort((a, b) => a.key.localeCompare(b.key, "en"))
  for (const t of templates) {
    const page = jobPage(t, lib, byKey)
    const file = put(`jobs/${t.product}/${t.key}`, page)
    toc.jobs.push({ key: t.key, product: t.product, part: t.part, text: t.plain_text, file })
  }

  for (const page of guidesEn(lib)) {
    const file = put(`guides/${page.slug}`, page)
    toc.guides.push({ slug: page.slug, h1: page.h1, file })
  }

  for (const edition of ["firm", "institution"]) {
    const page = landingHi(edition)
    const file = put(`hi/dpdp-${edition}`, page)
    toc.hi.push({ h1: page.h1, file })
  }
  for (const page of guidesHi(lib)) {
    const file = put(`hi/guides/${page.slug}`, page)
    toc.hi.push({ h1: page.h1, file })
  }

  out.set("INDEX.md", renderIndex(lib, toc))
  return { lib, files: out }
}

function renderIndex(lib, toc) {
  const byProduct = (p) => toc.jobs.filter((j) => j.product === p).map((j) => `- Part ${j.part} · [${j.key}](${j.file}) — ${j.text}`).join("\n")
  return `<!-- Generated by scripts/generate-job-pages.mjs -- do not hand-edit. -->

# DPDP drafts — index (UNPUBLISHED, pending lawyer review)

Library: \`${LIBRARY_FILE}\` version ${lib.version}, exported ${lib.exportedAt}.
Job pages: ${toc.jobs.length} · Guides: ${toc.guides.length} · Hindi drafts: ${toc.hi.length}.
Every page is a draft until the owner confirms lawyer review — see README.md.

## Guides (English)

${toc.guides.map((g) => `- [${g.h1}](${g.file})`).join("\n")}

## Hindi machine drafts (need human review before publishing)

${toc.hi.map((g) => `- [${g.h1}](${g.file})`).join("\n")}

## Job pages — companies, firms and NGOs (product \`firm\`)

${byProduct("firm")}

## Job pages — schools (product \`institution\`)

${byProduct("institution")}
`
}

function walk(dir) {
  const out = []
  if (!existsSync(dir)) return out
  for (const name of readdirSync(dir)) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) out.push(...walk(p))
    else out.push(p)
  }
  return out
}

function main() {
  const args = new Set(process.argv.slice(2))
  if (args.has("--print-tables")) {
    process.stdout.write(JSON.stringify({ LAWS, PARTS, AREA_HELP }) + "\n")
    return 0
  }

  const { files } = buildDrafts()

  if (args.has("--check")) {
    const problems = []
    for (const [rel, body] of files) {
      const abs = join(DRAFTS_DIR, rel)
      if (!existsSync(abs)) { problems.push(`missing: drafts/${rel}`); continue }
      const onDisk = readFileSync(abs, "utf8").replace(/\r\n/g, "\n")
      if (onDisk !== body) problems.push(`differs: drafts/${rel}`)
    }
    // Stale files: anything generated-looking under drafts/ that the
    // generator no longer produces (a job removed from the library).
    for (const abs of walk(DRAFTS_DIR)) {
      const rel = relative(DRAFTS_DIR, abs).split("\\").join("/")
      if (rel === "README.md") continue
      if (!files.has(rel)) problems.push(`stale (not generated any more): drafts/${rel}`)
    }
    if (problems.length) {
      console.error(`drafts are out of date (${problems.length} problem(s)) -- run: node scripts/generate-job-pages.mjs`)
      for (const p of problems) console.error("  " + p)
      return 1
    }
    console.log(`drafts up to date: ${files.size} files match the generator's output`)
    return 0
  }

  let written = 0
  for (const [rel, body] of files) {
    const abs = join(DRAFTS_DIR, rel)
    mkdirSync(dirname(abs), { recursive: true })
    const existing = existsSync(abs) ? readFileSync(abs, "utf8") : null
    if (existing !== body) { writeFileSync(abs, body, "utf8"); written++ }
  }
  console.log(`generated ${files.size} draft files under ${relative(process.cwd(), DRAFTS_DIR) || "."} (${written} written, ${files.size - written} unchanged)`)
  return 0
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = main()
}
