const sectionsHtml = (sections) =>
  sections
    .map((s) => {
      const out = [`  <section class="facts-section">`, `    <h2>${esc(s.h2)}</h2>`]
      for (const p of s.paragraphs ?? []) out.push(`    <p>${esc(p)}</p>`)
      if (s.bullets) out.push(`    <ul>`, ...s.bullets.map((b) => `      <li>${esc(b)}</li>`), `    </ul>`)
      out.push(`  </section>`)
      return out.join("\n")
    })
    .join("\n")

const sectionsMarkdown = (sections) =>
  sections
    .map((s) => {
      const out = [`## ${s.h2}`, ""]
      for (const p of s.paragraphs ?? []) out.push(p, "")
      if (s.bullets) out.push(...s.bullets.map((b) => `- ${b}`), "")
      return out.join("\n")
    })
    .join("\n")

function page(facts, { path, description, nodes, hidden = false, shareAsk, markdownAlternate = false, body }) {
  return [
    `<!doctype html>`,
    `<html lang="en-IN">`,
    `  <head>`,
    head(facts, { path, title: pageTitle(facts, path), description, nodes, hidden, markdownAlternate }),
    `  </head>`,
    `  <body class="site">`,
    `    <!-- BEGIN generated: brand-line -->`,
    indent(brandLine(facts, { shareAsk }), 4),
    `    <!-- END generated: brand-line -->`,
    indent(nav(facts, path), 4),
    indent(body, 4),
    indent(footer(facts), 4),
    `  </body>`,
    `</html>`,
    ``,
  ].join("\n")
}

const indent = (s, n) => s
  .split("\n")
  .map((l) => (l.length ? " ".repeat(n) + l : l))
  .join("\n")

