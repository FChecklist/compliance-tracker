function makeIdempotent(sql, tag) {
  let out = sql

  // CREATE TYPE ... AS ENUM(...); -> wrap in DO/EXCEPTION
  out = out.replace(
    /CREATE TYPE ("dpdp"\."\w+")\s+AS ENUM\(([^)]*)\);/g,
    (_m, name, vals) =>
      `DO $$ BEGIN\n  CREATE TYPE ${name} AS ENUM(${vals});\nEXCEPTION WHEN duplicate_object THEN NULL; END $$;`,
  )

  // CREATE TABLE "dpdp"."x" ( -> CREATE TABLE IF NOT EXISTS
  out = out.replace(/CREATE TABLE ("dpdp"\."\w+")\s*\(/g, "CREATE TABLE IF NOT EXISTS $1 (")

  // ALTER TABLE ... ADD COLUMN "x" -> ADD COLUMN IF NOT EXISTS "x"
  out = out.replace(/ADD COLUMN ("(?!IF NOT EXISTS)\w+")/g, "ADD COLUMN IF NOT EXISTS $1")

  // ALTER TABLE ... ADD CONSTRAINT "name" CHECK (...); -> wrap in DO/EXCEPTION
  out = out.replace(
    /ALTER TABLE ("dpdp"\."\w+") ADD CONSTRAINT ("\w+")\s*\n?\s*(CHECK[^;]+);/g,
    (_m, table, cname, check) =>
      `DO $$ BEGIN\n  ALTER TABLE ${table} ADD CONSTRAINT ${cname} ${check};\nEXCEPTION WHEN duplicate_object THEN NULL; END $$;`,
  )

  // CREATE TRIGGER x ... -> CREATE OR REPLACE TRIGGER x ... (PG14+, this project is on PG17)
  out = out.replace(/CREATE TRIGGER (\w+)/g, "CREATE OR REPLACE TRIGGER $1")

  return `-- ============================================================\n-- ${tag}\n-- ============================================================\n${out}`
}

