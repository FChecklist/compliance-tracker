#!/usr/bin/env node
// Phase 3 CI enforcement wiring (task-20260724-133911-terminology-phase3-ci-
// enforcement-wiring, instruction INS-20260724-133817-0a6d,
// ai-os/TERMINOLOGY_STANDARDIZATION_PHASE_PLAN_2026-07-24.yaml
// phase_3_ci_enforcement_wiring). Same enforcement class as
// check-asset-registry-coverage.mjs / check-guardrail-presence.mjs: a
// reviewable-diff ratchet enforced in CI, not a runtime-unbypassable lock --
// named honestly, not oversold.
//
// Ports ai-os/TERMINOLOGY_GUARDRAIL_2026-07-24.py's literal-shape scanning
// (the claude-control repo's Phase 0 design + Phase 1/2 rollout tool) to
// this repo's own bun/node toolchain, matching the other three coverage-gate
// jobs (guardrail-presence, asset-registry-coverage, metadata-index-coverage
// are all .mjs -- this would otherwise be the only python3 step in an
// all-JS coverage-gate suite).
//
// Honest limitation vs. the ported .py original: this script does NOT port
// the dictionary-backed checks (unregistered <Entity.Attribute> placeholder-
// token drift, dictionary_gap_candidate tagging). Those need
// ai-os/VARIABLE_DICTIONARY_2026-07-24.yaml and DATABASE_CATALOG.json, both
// claude-control-repo artifacts that do not exist in this repo's checkout --
// wiring them in would mean vendoring a second repo's generated data into
// this one just to run CI, a heavier cross-repo dependency than this phase's
// own scope (CI enforcement wiring) calls for. What ported cleanly is the
// six PATTERN_FAMILIES literal-shape checks (placeholder company/person
// names, placeholder email domains, bare ISO dates, Indian PAN/GSTIN literal
// shapes) -- identical regexes to the .py original.
//
// PHASE 4 CROSS-LINK (task-20260724-143013-phase4-migrate-existing-
// hardcoded-exampl, phase_4_existing_hardcoded_example_migration): for the
// same reason above, --suggest-fix (searching VARIABLE_DICTIONARY_2026-07-
// 24.yaml for a matching <Entity.Attribute> placeholder per finding) was
// added to the claude-control .py original, NOT ported here -- it is a
// dictionary-backed check, the same class this script already declines to
// port. Run it from a claude-control checkout against this repo's files:
//   python3 ai-os/TERMINOLOGY_GUARDRAIL_2026-07-24.py --suggest-fix --file <path in this repo>
// This file's own exemption manifest (ai-os/registry/terminology-guardrail-
// exemptions.yaml) records each Phase 4 migration/exemption decision that
// tool's suggestions (plus direct human review) led to.
//
// PHASE 5 UPDATE (task-20260724-220012-phase5-full-repo-wide-enforcement-
// dictio, phase_5_full_enforcement_and_dictionary_completion):
//   1. SCANNABLE_EXT_RE widened past .ts/.tsx to .md/.yaml/.yml/.json --
//      this phase's own scope note is that "company names, person names,
//      dates apply equally to prose docs," not just prompt/template code.
//   2. Scope widened from --diff-only to a --full-repo scan on every run
//      (ci.yml now invokes --full-repo, not --diff-only -- the flag still
//      exists and still works for local/manual use). This is only safe
//      because ai-os/registry/terminology-guardrail-exemptions.yaml was
//      regenerated this phase from one real, current, full-repo scan
//      (every scannable file, not just Phase 2's 4 priority directories) --
//      see that file's own header for why literal deletion of the manifest
//      (the plan's "retire the exemption file" wording, read most literally)
//      would have just broken CI on ~2200 pre-existing, non-migratable
//      matches instead of producing a working full-repo gate.
// Gating: ai-os/registry/terminology-guardrail-exemptions.yaml records, per
// file, the MAXIMUM allowed finding count per category (now a full-repo
// baseline, generated by
// ai-os-scripts/phase5_generate_full_repo_exemptions.py in the
// claude-control repo, not hand-typed). A re-scanned file's current count
// per category may not EXCEED that recorded baseline -- exceeding it means
// new debt, which fails CI; a file with no exemption entry at all must have
// zero findings. This is a count ratchet, not an exact-instance match: a PR
// that deletes one pre-existing finding and introduces a different one in
// the same file/category, holding the count static, is not caught by this
// check. That tradeoff is deliberate -- exact line/text matching would be
// brittle against line-shift from unrelated edits in the same file; the
// honestly weaker guarantee that IS made is "the total named-category debt
// in a file cannot grow silently."
//
// Usage:
//   node scripts/check-terminology-guardrail.mjs --full-repo
//   node scripts/check-terminology-guardrail.mjs --diff-only
//   node scripts/check-terminology-guardrail.mjs --file <path> [--file <path> ...]
//   node scripts/check-terminology-guardrail.mjs --file-list <path>
// Exit code: 0 if no NEW (unexempted) findings, 1 otherwise.
import { readFile, access } from "node:fs/promises"
import { execSync } from "node:child_process"
import path from "node:path"
import yaml from "js-yaml"

const REPO_ROOT = process.cwd()
const EXEMPTIONS_FILE = "ai-os/registry/terminology-guardrail-exemptions.yaml"
const BASE_BRANCH = process.env.GITHUB_BASE_REF || "main"
const SCANNABLE_EXT_RE = /\.(ts|tsx|md|ya?ml|json)$/

// Each pattern targets a concrete literal shape, never placeholder syntax
// itself (placeholders use <Entity.Attribute>, these patterns match plain
// text) -- so by construction any match here is a hardcoded literal, not a
// registered placeholder. Identical to TERMINOLOGY_GUARDRAIL_2026-07-24.py's
// own PATTERN_FAMILIES.
const PATTERN_FAMILIES = [
  [
    "placeholder_company_name",
    /\b(ABC|XYZ|Acme|Foo|Bar)\s+(Corp\.?|Corporation|Pvt\.?\s*Ltd\.?|Private Limited|Ltd\.?|LLP|Inc\.?|Company)\b/g,
    "Hardcoded placeholder-style company name -- replace with a registered <Entity.Attribute> " +
      "placeholder (e.g. <Clients.Name>) instead of a literal example company.",
  ],
  [
    "placeholder_person_name",
    /\b(John|Jane)\s+(Doe|Smith)\b/g,
    "Hardcoded placeholder-style person name -- replace with a registered <Entity.Attribute> " +
      "placeholder (e.g. <Users.Name>) instead of a literal example person.",
  ],
  [
    "placeholder_email_domain",
    /\b[a-zA-Z0-9_.+-]+@(example|acme|test|foo|sample)\.(com|org|net)\b/gi,
    "Hardcoded placeholder-style email address -- replace with a registered <Entity.Attribute> " +
      "placeholder (e.g. <Users.Email>) instead of a literal example address.",
  ],
  [
    "hardcoded_iso_date",
    /\b\d{4}-\d{2}-\d{2}\b/g,
    "Bare ISO date literal -- if this is example/sample data (not a real changelog/version/task-id " +
      "date), replace with a registered date-typed <Entity.Attribute> placeholder.",
  ],
  [
    "indian_pan_literal",
    /\b[A-Z]{5}[0-9]{4}[A-Z]\b/g,
    "Literal shaped like an Indian PAN number -- replace with a registered <Entity.Attribute> " +
      "placeholder rather than a hand-typed example PAN.",
  ],
  [
    "indian_gstin_literal",
    /\b\d{2}[A-Z]{5}\d{4}[A-Z][1-9A-Z]Z[0-9A-Z]\b/g,
    "Literal shaped like an Indian GSTIN -- replace with a registered <Entity.Attribute> placeholder " +
      "rather than a hand-typed example GSTIN.",
  ],
]

function scanText(text, sourceLabel) {
  const findings = []
  const lines = text.split("\n")
  lines.forEach((line, idx) => {
    for (const [category, pattern, note] of PATTERN_FAMILIES) {
      const re = new RegExp(pattern.source, pattern.flags)
      let m
      while ((m = re.exec(line)) !== null) {
        findings.push({
          source: sourceLabel,
          line: idx + 1,
          column: m.index + 1,
          category,
          matched_text: m[0],
          note,
          line_excerpt: line.trim().slice(0, 160),
        })
        if (m[0].length === 0) re.lastIndex += 1
      }
    }
  })
  return findings
}

async function scanFile(relPath) {
  // PHASE 5 ADDITION: the exemptions manifest itself is guardrail
  // configuration, not prompt/template code or prose documentation -- its
  // own reason text legitimately repeats literal dates and category names
  // (e.g. "(2026-07-24)" once per entry) to record when/why each permanent
  // exemption was decided, which is exactly the shape this scanner looks
  // for. Scanning it against itself would be circular (its findings could
  // never be recorded in itself) and is out of this guardrail's actual
  // scope (it targets AI prompt/template + prose content, not the
  // guardrail's own bookkeeping), so it is always skipped -- same
  // "wrong tool for this content" reasoning as the seed/test-fixture and
  // static-preview-data exemptions already recorded inside it.
  if (relPath === EXEMPTIONS_FILE) return null

  const abs = path.resolve(REPO_ROOT, relPath)
  try {
    await access(abs)
  } catch {
    return null // deleted file, nothing to scan
  }
  const text = await readFile(abs, "utf8")
  return scanText(text, relPath)
}

function getDiffFiles() {
  try {
    execSync(`git fetch origin ${BASE_BRANCH} --depth=100`, { stdio: "ignore" })
  } catch {
    // best-effort -- checkout may already have the ref, or fetch may be
    // unavailable (e.g. no network in a local test run); merge-base below
    // falls back if this didn't help.
  }
  let mergeBase = null
  for (const ref of [`origin/${BASE_BRANCH}`, BASE_BRANCH]) {
    try {
      mergeBase = execSync(`git merge-base HEAD ${ref}`, { encoding: "utf8" }).trim()
      if (mergeBase) break
    } catch {
      // try next ref candidate
    }
  }
  if (!mergeBase) {
    try {
      mergeBase = execSync(`git rev-parse HEAD~1`, { encoding: "utf8" }).trim()
    } catch {
      return null
    }
  }

  const tracked = execSync(`git diff --name-only --diff-filter=ACMR ${mergeBase} HEAD`, { encoding: "utf8" })
    .trim()
  const untracked = execSync(`git ls-files --others --exclude-standard`, { encoding: "utf8" }).trim()

  const files = new Set()
  for (const f of [...tracked.split("\n"), ...untracked.split("\n")]) {
    if (f) files.add(f)
  }
  return [...files].filter((f) => SCANNABLE_EXT_RE.test(f))
}

function getFullRepoFiles() {
  // PHASE 5 ADDITION: every git-tracked file in the repo, not just this PR's
  // diff -- the --full-repo CI mode this phase wires in. Tracked files only
  // (matches getDiffFiles's own tracked+untracked-but-not-ignored intent
  // closely enough for CI, where the working tree is a fresh checkout with
  // no stray untracked files); a deleted-on-disk edge case is impossible
  // here since we're listing files that exist by construction.
  let tracked
  try {
    tracked = execSync("git ls-files", { encoding: "utf8" }).trim()
  } catch (err) {
    console.error(`Could not list repo files via git ls-files (${err.message}) -- failing closed.`)
    return null
  }
  if (!tracked) return []
  return tracked.split("\n").filter((f) => f && SCANNABLE_EXT_RE.test(f))
}

async function loadExemptions() {
  try {
    const raw = await readFile(path.resolve(REPO_ROOT, EXEMPTIONS_FILE), "utf8")
    const doc = yaml.load(raw)
    const byFile = new Map()
    for (const entry of doc?.exemptions ?? []) {
      byFile.set(entry.file, entry.findings_by_category ?? {})
    }
    return byFile
  } catch (err) {
    console.error(`WARNING: could not load ${EXEMPTIONS_FILE} (${err.message}) -- treating as no exemptions.`)
    return new Map()
  }
}

async function main() {
  const args = process.argv.slice(2)
  const diffOnly = args.includes("--diff-only")
  const fullRepo = args.includes("--full-repo")
  const explicitFiles = []
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--file") explicitFiles.push(args[++i])
  }
  const fileListIdx = args.indexOf("--file-list")
  if (fileListIdx !== -1) {
    const listPath = args[fileListIdx + 1]
    const raw = await readFile(path.resolve(REPO_ROOT, listPath), "utf8")
    for (const line of raw.split("\n")) {
      const trimmed = line.trim()
      if (trimmed && !trimmed.startsWith("#")) explicitFiles.push(trimmed)
    }
  }

  let filesToScan
  if (fullRepo) {
    filesToScan = getFullRepoFiles()
    if (filesToScan === null) {
      console.error("Could not list repo files for a full-repo scan -- failing closed.")
      process.exit(1)
    }
  } else if (diffOnly) {
    filesToScan = getDiffFiles()
    if (filesToScan === null) {
      console.error("Could not determine a diff base (no merge-base, no HEAD~1) -- failing closed.")
      process.exit(1)
    }
  } else if (explicitFiles.length > 0) {
    filesToScan = explicitFiles
  } else {
    console.error(
      "Usage: check-terminology-guardrail.mjs --full-repo | --diff-only | --file <path> [...] | --file-list <path>"
    )
    process.exit(1)
  }

  const exemptions = await loadExemptions()

  let newFindingsTotal = 0
  const report = []

  for (const relPath of filesToScan) {
    const findings = await scanFile(relPath)
    if (findings === null || findings.length === 0) continue

    const currentByCategory = {}
    for (const f of findings) {
      currentByCategory[f.category] = (currentByCategory[f.category] ?? 0) + 1
    }

    const baseline = exemptions.get(relPath) ?? {}
    const newByCategory = {}
    let fileHasNew = false
    for (const [category, count] of Object.entries(currentByCategory)) {
      const allowed = baseline[category] ?? 0
      if (count > allowed) {
        newByCategory[category] = { current: count, allowed, excess: count - allowed }
        newFindingsTotal += count - allowed
        fileHasNew = true
      }
    }

    if (fileHasNew) {
      report.push({ file: relPath, newByCategory, findings })
    }
  }

  if (newFindingsTotal > 0) {
    console.error("=== Terminology Guardrail Check FAILED ===")
    console.error(
      `${newFindingsTotal} new (unexempted) hardcoded-example finding(s) across ${report.length} file(s):\n`
    )
    for (const { file, newByCategory, findings } of report) {
      console.error(`  --- ${file} ---`)
      for (const [category, { current, allowed, excess }] of Object.entries(newByCategory)) {
        console.error(`    ${category}: ${current} found, ${allowed} exempted, ${excess} new`)
      }
      for (const f of findings.filter((f) => f.category in newByCategory)) {
        console.error(`      line ${f.line}: "${f.matched_text}" -- ${f.line_excerpt}`)
      }
    }
    console.error(
      "\nReplace new hardcoded examples with a registered <Entity.Attribute> placeholder from " +
        "ai-os/VARIABLE_DICTIONARY_2026-07-24.yaml (claude-control repo), or, if this is a deliberate " +
        `exemption (e.g. a seed/test fixture), add/raise the count in ${EXEMPTIONS_FILE} with a real reason.`
    )
    process.exit(1)
  }

  console.log(
    `Terminology Guardrail Check passed -- ${filesToScan.length} file(s) scanned, no new hardcoded-example findings.`
  )
}

main().catch((err) => {
  console.error("Terminology Guardrail Check crashed:", err)
  process.exit(1)
})
