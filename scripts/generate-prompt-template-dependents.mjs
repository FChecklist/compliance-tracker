// T2-01 fix (2026-09-12): prompt-governance-service.ts's
// getPromptTemplateDependents() used to walk src/ at REQUEST TIME via
// readdirSync/readFileSync -- confirmed via this repo's own `next build`
// output (route.js.nft.json for the settings/prompts route traces zero
// files under src/) that this walk finds NOTHING on real Vercel production,
// because Vercel's file-tracer cannot see files reached only via a dynamic,
// non-imported directory walk. The walk's own try/catch silently swallowed
// the resulting ENOENT and returned an empty array -- a wrong answer that
// looks exactly like a real "zero dependents" answer to an operator
// promoting a prompt template through the lifecycle state machine.
//
// This script does the SAME src/ walk, but at BUILD TIME, and emits a
// statically-importable generated map (src/lib/generated/
// prompt-template-dependents.generated.ts) that
// getPromptTemplateDependents() reads via a real `import` -- so Vercel's
// file-tracer includes it exactly the way it includes any other module a
// route imports, closing the gap for good rather than papering over it.
//
// Run via `bun run predev`/`prebuild` (see package.json) -- regenerates the
// output file every time before dev/build, same pattern as
// scripts/generate-protected-routes.mjs.
import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs"
import { join, dirname, sep } from "node:path"
import { fileURLToPath } from "node:url"

const __dirname = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = join(__dirname, "..")
const SCAN_ROOT = join(REPO_ROOT, "src")
const OUT_FILE = join(REPO_ROOT, "src", "lib", "generated", "prompt-template-dependents.generated.ts")

const SCAN_EXTENSIONS = new Set([".ts", ".tsx"])
const SCAN_IGNORE_DIRS = new Set(["node_modules", ".next", "dist"])

// Same exclusions the old runtime walk used: this generator's own output
// file/this service file's docstrings mention resolvePromptTemplate()
// literally, and a *.test.ts(x) fixture asserting against a templateKey
// string is not a real application dependency on that prompt -- both would
// otherwise false-positive as "dependents".
function isExcluded(relPath) {
  return (
    relPath.endsWith("prompt-governance-service.ts") ||
    relPath.endsWith(".test.ts") ||
    relPath.endsWith(".test.tsx") ||
    relPath.includes(`generated${sep}prompt-template-dependents.generated`)
  )
}

let scannedFileCount = 0

function* walkSourceFiles(dir) {
  let entries
  try {
    entries = readdirSync(dir, { withFileTypes: true })
  } catch {
    return
  }
  for (const entry of entries) {
    if (SCAN_IGNORE_DIRS.has(entry.name)) continue
    const full = join(dir, entry.name)
    if (entry.isDirectory()) {
      yield* walkSourceFiles(full)
    } else if (SCAN_EXTENSIONS.has(entry.name.slice(entry.name.lastIndexOf(".")))) {
      scannedFileCount++
      yield full
    }
  }
}

// Matches resolvePromptTemplate("literal.key") / resolvePromptTemplate('literal.key')
// -- deliberately only a string-literal argument (a dynamic/computed
// templateKey call site can't be attributed to one specific key at build
// time, same limitation the old runtime regex-based match had).
const CALL_SITE_PATTERN = /resolvePromptTemplate\(\s*(['"])((?:(?!\1).)+)\1/g

/** @type {Record<string, Set<string>>} */
const dependentsByTemplateKey = {}

for (const file of walkSourceFiles(SCAN_ROOT)) {
  const relPath = file.slice(REPO_ROOT.length + 1).split(sep).join("/")
  if (isExcluded(relPath)) continue

  let content
  try {
    content = readFileSync(file, "utf8")
  } catch {
    continue
  }
  if (!content.includes("resolvePromptTemplate(")) continue

  let match
  CALL_SITE_PATTERN.lastIndex = 0
  while ((match = CALL_SITE_PATTERN.exec(content)) !== null) {
    const templateKey = match[2]
    if (!dependentsByTemplateKey[templateKey]) dependentsByTemplateKey[templateKey] = new Set()
    dependentsByTemplateKey[templateKey].add(relPath)
  }
}

if (scannedFileCount < 50) {
  console.error(
    `generate-prompt-template-dependents: scanned only ${scannedFileCount} source file(s) under ${SCAN_ROOT} -- refusing to write a map from what looks like an empty/unreachable tree (this repo genuinely has tens of thousands of .ts/.tsx files under src/).`
  )
  process.exit(1)
}

/** @type {Record<string, string[]>} */
const outputMap = {}
for (const [templateKey, files] of Object.entries(dependentsByTemplateKey)) {
  outputMap[templateKey] = [...files].sort()
}

const generatedAt = new Date().toISOString()

const content = `// AUTO-GENERATED by scripts/generate-prompt-template-dependents.mjs -- do
// not edit by hand, it will be overwritten on the next dev/build.
//
// T2-01 (2026-09-12): this is the build-time-computed replacement for the
// old request-time fs walk in prompt-governance-service.ts's
// getPromptTemplateDependents(), which silently returned an empty array on
// real Vercel production (Vercel's file-tracer cannot see a dynamic
// directory walk -- see that file's own header comment for the full RCA).
// Statically imported, so the file-tracer includes it like any other
// module a route imports.
//
// Map shape: templateKey (the literal string argument passed to
// resolvePromptTemplate() somewhere in src/) -> sorted list of repo-relative
// file paths (forward-slash-normalized) that call it.
export const PROMPT_TEMPLATE_DEPENDENTS: Record<string, string[]> = ${JSON.stringify(outputMap, null, 2)}

// Generation metadata -- getPromptTemplateDependents() uses SOURCE_FILE_COUNT
// as a plausibility floor (a map generated against an empty/unreachable tree
// would have a near-zero count) to decide whether this map can be trusted at
// all, rather than ever silently treating "no entry for this key" the same
// as "the map itself is untrustworthy".
export const GENERATED_AT: string = ${JSON.stringify(generatedAt)}
export const SOURCE_FILE_COUNT: number = ${scannedFileCount}

export default PROMPT_TEMPLATE_DEPENDENTS
`

const outDir = dirname(OUT_FILE)
if (!existsSync(outDir)) mkdirSync(outDir, { recursive: true })
writeFileSync(OUT_FILE, content, "utf8")

const totalDependentEdges = Object.values(outputMap).reduce((sum, files) => sum + files.length, 0)
console.log(
  `generate-prompt-template-dependents: scanned ${scannedFileCount} source file(s), found ${Object.keys(outputMap).length} distinct templateKey(s) / ${totalDependentEdges} dependent edge(s). Wrote ${OUT_FILE}`
)
