#!/usr/bin/env node
// VERIDIAN Review Framework gap-closure, 2026-08-15: "AI Can Generate Tests
// for Module" flagged "No systematic test-generation tooling" (recommended
// approach: "Add a coverage-gap report ... to prioritize which untested
// files to target next"). This is that report.
//
// Scope: src/lib/services/*.ts -- the business-logic layer this codebase's
// own convention already concentrates tests in (as of this writing, 48 of
// 184 service files have a sibling <name>.test.ts; every service test in
// the repo lives here, e.g. crm-accounts-service.test.ts,
// software-coverage-service.test.ts, gst-reconciliation-engine.test.ts).
// Not the whole src/lib tree: a lot of that is genuinely non-business-logic
// (ai-team roster config, prompt-cache plumbing, webhook glue) where a
// sibling-test convention was never established, so flagging it as a "gap"
// against a convention that was never adopted there would be noise, not
// signal.
//
// "Has a test" is approximated the same way scripts/check-new-test-
// coverage.mjs's CI gate approximates it: a sibling `<name>.test.ts` file
// in the same directory. This is a real, cheap, honest proxy for "someone
// wrote unit tests targeting this file" -- it is NOT the same claim as
// "this file has N% line coverage" (bun test --coverage instrumentation
// tells you that, but only for files a test actually imports, so it can't
// answer "which UNTESTED files should I target next" -- there's nothing
// to instrument). A file could still have low real coverage despite having
// a sibling test; this report's job is triaging the "zero tests exist at
// all" tier, not measuring depth within files that already clear that bar.
//
// Priority order is untested files sorted by line count, descending --
// the same signal the "AI Can Safely Understand Module" finding flagged
// (understanding quality varies with file size): a large untested file is
// both the hardest to safely modify/refactor blind AND the highest-value
// target once a test is added, so one ranking serves both findings.
//
// Usage:
//   node scripts/report-test-coverage-gap.mjs            # writes the report
//   node scripts/report-test-coverage-gap.mjs --check     # exit 1 if the
//     committed report is stale vs the current repo state (CI drift guard)
//   node scripts/report-test-coverage-gap.mjs --top=20    # change how many
//     rows the "top priority" table shows (default 20)
//
// buildStats()/renderReport() below are pure (no fs access) so they're unit
// tested directly with fixture data in report-test-coverage-gap.test.ts --
// only the top-level script body below does real file I/O.

import { readFileSync, readdirSync, writeFileSync } from "node:fs"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

export const SERVICES_LABEL = "src/lib/services"

/**
 * Pure classification: given every filename present in the services
 * directory and a lineCounts map (filename -> line count) for the non-test
 * .ts files, returns coverage stats. No fs access -- easy to unit test.
 */
export function buildStats(allFileNames, lineCounts) {
  const testFileSet = new Set(allFileNames.filter((f) => f.endsWith(".test.ts")))
  const serviceFiles = allFileNames.filter((f) => f.endsWith(".ts") && !f.endsWith(".test.ts"))
  const rows = serviceFiles.map((f) => {
    const base = f.slice(0, -3) // strip ".ts"
    return {
      file: `${SERVICES_LABEL}/${f}`,
      lines: lineCounts[f] ?? 0,
      hasTest: testFileSet.has(`${base}.test.ts`),
    }
  })
  const testedCount = rows.filter((r) => r.hasTest).length
  // Secondary sort key (filename, ascending) makes tie-breaking deterministic:
  // readdirSync()'s listing order is filesystem/OS-dependent (Windows NTFS vs
  // Linux ext4 don't guarantee the same order), so without a tiebreaker, two
  // files with an identical line count could land in a different relative
  // order depending on which OS generated the report -- causing --check to
  // spuriously report the committed doc as "stale" on CI (Linux) even when a
  // local regen (Windows) produced byte-identical content modulo tie order.
  // Real bug found + fixed 2026-08-30 (PR #1472's CI hit exactly this).
  const untested = rows
    .filter((r) => !r.hasTest)
    .sort((a, b) => b.lines - a.lines || a.file.localeCompare(b.file))
  return { total: rows.length, testedCount, untested }
}

/** Pure: renders the markdown report from stats. No fs access. */
export function renderReport({ total, testedCount, untested }, topN) {
  const pct = total === 0 ? "0.0" : ((testedCount / total) * 100).toFixed(1)
  const top = untested.slice(0, topN)
  const lines = []
  lines.push("# Test Coverage Gap Report — src/lib/services")
  lines.push("")
  lines.push(
    "<!-- AUTO-GENERATED by scripts/report-test-coverage-gap.mjs -- do not hand-edit. -->"
  )
  lines.push(
    "<!-- Regenerate with: node scripts/report-test-coverage-gap.mjs -->"
  )
  lines.push("")
  lines.push(
    "VERIDIAN Review Framework gap-closure (\"AI Can Generate Tests for Module\": " +
      "\"No systematic test-generation tooling\"). Coverage here means \"has a " +
      "sibling `<name>.test.ts` file\", not line-coverage percentage -- see this " +
      "script's own header for why that's the right proxy for triaging files with " +
      "ZERO tests. Files are ranked by line count because the largest untested " +
      "files are both the riskiest to modify/refactor blind (\"AI Can Safely " +
      "Modify/Refactor Module\" findings) and the highest-value next target."
  )
  lines.push("")
  lines.push(`**Summary:** ${testedCount}/${total} service files have a sibling test file (${pct}%).`)
  lines.push("")
  lines.push(`## Top ${top.length} untested files by size (highest priority first)`)
  lines.push("")
  lines.push("| Rank | File | Lines |")
  lines.push("|------|------|-------|")
  top.forEach((r, i) => {
    lines.push(`| ${i + 1} | \`${r.file}\` | ${r.lines} |`)
  })
  lines.push("")
  lines.push(`_Total untested files (all sizes): ${untested.length}. Showing top ${top.length}._`)
  lines.push("")
  return lines.join("\n")
}

// --- top-level script body (real fs I/O; not exercised by unit tests) ---
const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href
if (isMain) {
  const REPO_ROOT = fileURLToPath(new URL("..", import.meta.url))
  const SERVICES_DIR = path.join(REPO_ROOT, "src/lib/services")
  const REPORT_PATH = path.join(REPO_ROOT, "docs/master/TEST_COVERAGE_GAP.md")

  const args = process.argv.slice(2)
  const checkMode = args.includes("--check")
  const topArg = args.find((a) => a.startsWith("--top="))
  const topN = topArg ? Number.parseInt(topArg.split("=")[1], 10) : 20

  const allFileNames = readdirSync(SERVICES_DIR)
  const lineCounts = {}
  for (const f of allFileNames) {
    if (f.endsWith(".ts") && !f.endsWith(".test.ts")) {
      lineCounts[f] = readFileSync(path.join(SERVICES_DIR, f), "utf8").split("\n").length
    }
  }

  const stats = buildStats(allFileNames, lineCounts)
  const report = renderReport(stats, topN)

  if (checkMode) {
    let existing = ""
    try {
      existing = readFileSync(REPORT_PATH, "utf8")
    } catch {
      console.error(`ERROR: ${REPORT_PATH} does not exist. Run: node scripts/report-test-coverage-gap.mjs`)
      process.exit(1)
    }
    if (existing.trim() !== report.trim()) {
      console.error(
        "ERROR: docs/master/TEST_COVERAGE_GAP.md is stale (src/lib/services has changed " +
          "since it was last regenerated). Run: node scripts/report-test-coverage-gap.mjs " +
          "and commit the result."
      )
      process.exit(1)
    }
    console.log("OK: TEST_COVERAGE_GAP.md is up to date.")
    process.exit(0)
  }

  writeFileSync(REPORT_PATH, report)
  console.log(`Wrote ${REPORT_PATH} (${stats.testedCount}/${stats.total} service files tested).`)
}
