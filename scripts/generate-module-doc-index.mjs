#!/usr/bin/env node
// Gap closure, 2026-08-07 (VERIDIAN Review Framework, AI Documentation --
// UMR-20260801-170930-2080 sub-task): closes the [Low] "AI-Readable Module
// Documentation" finding. `docs/master/MODULE_MAP.md` already indexes
// domains at the module/service-file-list granularity; what didn't exist
// was a per-file index -- confirmed worth building because the underlying
// convention is real: every file in `src/lib/services/` opens with a
// leading `//` doc-comment block explaining its purpose (spot-checked;
// this generator itself skips files that don't have one rather than
// fabricating a summary).
//
// Two modes:
//   node scripts/generate-module-doc-index.mjs         -- regenerate the file
//   node scripts/generate-module-doc-index.mjs --check  -- CI mode: fails
//     (exit 1) if the checked-in file doesn't match what regenerating it
//     right now would produce, i.e. a new/changed service file's doc
//     comment drifted from the index without the index being refreshed.
//
// Honest limitation, same class as this repo's other check-*.mjs scripts:
// this only extracts the FIRST line of each file's leading comment block
// as a one-line summary -- it is a directory, not a substitute for reading
// the file. It only covers `src/lib/services/` (the directory with the
// confirmed consistent convention), not every directory in the repo.
import { readFile, readdir, writeFile } from "node:fs/promises"
import path from "node:path"

const REPO_ROOT = process.cwd()
const SERVICES_DIR = "src/lib/services"
const OUTPUT_PATH = "docs/master/MODULE_DOC_INDEX.md"

function extractLeadingSummary(src) {
  const lines = src.split("\n")
  const commentLines = []
  for (const line of lines) {
    const trimmed = line.trim()
    if (trimmed.startsWith("///")) continue // triple-slash reference directives, not doc comments
    if (trimmed.startsWith("//")) {
      commentLines.push(trimmed.replace(/^\/\/\s?/, ""))
      continue
    }
    break // first non-comment, non-reference line ends the leading block
  }
  if (commentLines.length === 0) return null
  // First sentence (up to the first ". " or the whole first line, whichever's shorter/cleaner).
  const joined = commentLines.join(" ")
  const firstSentenceMatch = joined.match(/^(.*?\.)\s/)
  return (firstSentenceMatch ? firstSentenceMatch[1] : commentLines[0]).trim()
}

async function buildIndex() {
  const entries = await readdir(path.resolve(REPO_ROOT, SERVICES_DIR), { withFileTypes: true })
  const files = entries
    .filter((e) => e.isFile() && e.name.endsWith(".ts") && !e.name.endsWith(".test.ts"))
    .map((e) => e.name)
    .sort()

  const rows = []
  let undocumented = 0
  for (const name of files) {
    const src = await readFile(path.resolve(REPO_ROOT, SERVICES_DIR, name), "utf8")
    const summary = extractLeadingSummary(src)
    if (summary) {
      rows.push(`| \`${name}\` | ${summary.replace(/\\/g, "\\\\").replace(/\|/g, "\\|")} |`)
    } else {
      undocumented++
      rows.push(`| \`${name}\` | _(no leading doc comment found)_ |`)
    }
  }

  const header = `# VERIDIAN AI OS — Module Doc Index (\`src/lib/services/\`)

**Generated by \`scripts/generate-module-doc-index.mjs\` -- do not hand-edit.** Closes the [Low]
"AI-Readable Module Documentation" finding (VERIDIAN Review Framework, AI Documentation
gap-closure, 2026-08-07): a per-file index of every service module's own leading doc comment,
one row per file, so a file's purpose is discoverable without opening it. Complements
\`docs/master/MODULE_MAP.md\`, which indexes at the domain (multi-file) granularity -- this is
the file-level drill-down. Run \`node scripts/generate-module-doc-index.mjs\` to refresh after
adding/renaming a service file; \`--check\` mode (wired into CI) fails the build if this file is
out of sync with the real leading comments.

${files.length} files indexed, ${undocumented} without a recognized leading \`//\` doc comment.

| File | Summary (first line/sentence of its leading comment) |
|---|---|
${rows.join("\n")}
`
  return header
}

async function main() {
  const checkMode = process.argv.includes("--check")
  const generated = await buildIndex()

  if (!checkMode) {
    await writeFile(path.resolve(REPO_ROOT, OUTPUT_PATH), generated)
    console.log(`Wrote ${OUTPUT_PATH}`)
    return
  }

  let existing = ""
  try {
    existing = await readFile(path.resolve(REPO_ROOT, OUTPUT_PATH), "utf8")
  } catch {
    console.error(`${OUTPUT_PATH} does not exist -- run without --check to generate it.`)
    process.exit(1)
  }

  if (existing !== generated) {
    console.error(
      `${OUTPUT_PATH} is out of sync with src/lib/services/ -- run ` +
      `'node scripts/generate-module-doc-index.mjs' and commit the result.`
    )
    process.exit(1)
  }
  console.log("OK: module doc index is up to date.")
}

main().catch((err) => {
  console.error(err)
  process.exit(1)
})
